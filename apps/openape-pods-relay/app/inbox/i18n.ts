export const dictionaries = { de, en }
export type Language = keyof typeof dictionaries

const storageKey = 'pods-inbox-language'
function stored(): Language | null {
  try { const value = localStorage.getItem(storageKey); return value === 'de' || value === 'en' ? value : null }
  catch { return null }
}
export function detectLanguage(languages: readonly string[]): Language {
  for (const tag of languages) {
    const base = tag.toLowerCase().split('-')[0]
    if (base === 'de' || base === 'en') return base
  }
  return 'de'
}

/** `null` follows the browser language. A per-viewer convenience; losing it only resets to automatic. */
export const languageChoice = ref<Language | null>(typeof window === 'undefined' ? null : stored())
export const language = computed<Language>(() => languageChoice.value ?? (typeof navigator === 'undefined' ? 'de' : detectLanguage(navigator.languages ?? [navigator.language])))
export function chooseLanguage(choice: Language | null): void {
  languageChoice.value = choice
  try { if (choice) localStorage.setItem(storageKey, choice); else localStorage.removeItem(storageKey) }
  catch { /* storage blocked: the choice lasts for this session only */ }
}

export function t(key: Key, values: Record<string, string | number> = {}): string {
  return dictionaries[language.value][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
}
export function formatTime(at: number | null): string {
  return at ? new Date(at).toLocaleString(language.value === 'de' ? 'de-AT' : 'en-GB', { dateStyle: 'short', timeStyle: 'short' }) : '—'
}
